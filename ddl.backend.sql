CREATE TABLE T_BEE_CHAT_MSG
(
    ID             BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '主键',
    WECHAT_ID      VARCHAR(128) COMMENT '微信ID',
    SENDER         VARCHAR(128) COMMENT '发送人(微信ID|群成员微信ID|模拟群成员微信ID)',
    RECEIVER       VARCHAR(128) COMMENT '接收人(微信ID|群ID|模拟群成员微信ID)',
    MSG_ID         VARCHAR(32) COMMENT '消息ID',
    CONTENT_TYPE   VARCHAR(16) COMMENT '消息类型(@枚举)',
    CONTENT        TEXT COMMENT '消息内容',
    SOURCE         TEXT COMMENT '消息来源(前端不需要)',
    ORIGIN_CONTENT TEXT COMMENT '原始消息内容(前端不需要)',
    REVOKE_FLAG    VARCHAR(2) COMMENT '撤回标识(1:是,0:否)',
    SHIELD_FLAG    VARCHAR(2) COMMENT '屏蔽消息标识(前端不需要)(1:是,0:否)',
    CLIENT_FLAG    VARCHAR(2) COMMENT '客户端消息标识(1:是,0:否)',
    SEND_USER_ID   VARCHAR(32) COMMENT '发送用户ID',
    CREATE_BY      VARCHAR(32) COMMENT '创建人',
    CREATE_TIME    DATETIME COMMENT '创建时间',
    UPDATE_BY      VARCHAR(32) COMMENT '修改人',
    UPDATE_TIME    DATETIME COMMENT '修改时间',
    UNIQUE INDEX IX_T_BEE_CHAT_MSG_WI(WECHAT_ID, MSG_ID),
    INDEX          IX_T_BEE_CHAT_MSG_S(SENDER),
    INDEX          IX_T_BEE_CHAT_MSG_R(RECEIVER),
    INDEX          IX_T_BEE_CHAT_MSG_MI(MSG_ID),
    INDEX          IX_T_BEE_CHAT_MSG_CT(CONTENT_TYPE)
) COMMENT='消息表' COLLATE=UTF8MB4_UNICODE_CI;

