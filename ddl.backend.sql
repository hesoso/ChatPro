CREATE TABLE T_BEE_CHAT_CONTACT
(
    ID                BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '主键',
    WECHAT_ID         VARCHAR(128) COMMENT '微信ID',
    CONTACT_WECHAT_ID VARCHAR(128) COMMENT '联系人微信ID',
    CONTACT_NO        VARCHAR(128) COMMENT '联系人微信号',
    CONTACT_NICKNAME  VARCHAR(256) COMMENT '联系人微信昵称',
    CONTACT_AVATAR    VARCHAR(256) COMMENT '联系人微信头像',
    REMARK            VARCHAR(128) COMMENT '备注',
    CONTACT_TYPE      VARCHAR(2) COMMENT '联系人类型(1:个微联系人,2:企业联系人,3:内部联系人,4:外部联系人)',
    MOBILE            VARCHAR(32) COMMENT '电话',
    LABEL             TEXT COMMENT '标签($标签1$,$标签2$)',
    DESCRIPTION       VARCHAR(256) COMMENT '描述',
    GENDER            VARCHAR(2) COMMENT '性别(0:未知,1:男,2:女)',
    PROVINCE          VARCHAR(64) COMMENT '省份',
    CITY              VARCHAR(64) COMMENT '城市',
    COMPANY_ID        VARCHAR(64) COMMENT '公司ID',
    COMPANY_NAME      VARCHAR(64) COMMENT '公司名称',
    RELATION          VARCHAR(2) COMMENT '联系人关系(1:正常,0:已被删)',
    ADD_CONTACT_TIME  DATETIME COMMENT '添加为联系人时间',
    CREATE_BY         VARCHAR(32) COMMENT '创建人',
    CREATE_TIME       DATETIME COMMENT '创建时间',
    UPDATE_BY         VARCHAR(32) COMMENT '修改人',
    UPDATE_TIME       DATETIME COMMENT '修改时间',
    UNIQUE INDEX IX_T_BEE_CHAT_CONTACT_WC(WECHAT_ID,CONTACT_WECHAT_ID),
    INDEX             IX_T_BEE_CHAT_CONTACT_CWI(CONTACT_WECHAT_ID),
    INDEX             IX_T_BEE_CHAT_CONTACT_ACT(ADD_CONTACT_TIME)
) COMMENT='联系人表' COLLATE=UTF8MB4_UNICODE_CI;

